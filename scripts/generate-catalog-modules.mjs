// Bundles the markdown catalogs into a TypeScript module so the app can read them
// on runtimes without a filesystem (Cloudflare Workers).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const targets = [
  { source: "algeria_69_wilayas_tourism_master_catalog.md", symbol: "tourismDirectoryMarkdown" },
  { source: "public/algeria_tourism_hotels_near_attractions_master_catalog.md", symbol: "hotelCatalogMarkdown" },
];

const lines = ["// Generated by scripts/generate-catalog-modules.mjs. Do not edit by hand.", ""];
for (const target of targets) {
  const markdown = readFileSync(join(root, target.source), "utf8");
  lines.push(`export const ${target.symbol} = ${JSON.stringify(markdown)};`, "");
}

const output = join(root, "src", "lib", "catalog-content.generated.ts");
writeFileSync(output, lines.join("\n"), "utf8");
console.log(`Wrote ${output} (${targets.length} catalogs)`);
